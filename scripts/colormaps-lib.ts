// Pure helpers for scripts/build-colormaps.ts (no I/O, no imports, so they are easy to test).

export interface ReleaseInfo {
  version: string
  doi: string
  url: string
  file: string
  md5: string
  date: string
}

export const STOPS_PER_MAP = 256

/** 0-1 floats to "#rrggbb". */
export function floatsToHex(r: number, g: number, b: number): string {
  const part = (v: number): string => Math.round(v * 255).toString(16).padStart(2, '0')
  return `#${part(r)}${part(g)}${part(b)}`
}

/** Parse a Crameri colour map text file (one "r g b" line of 0-1 floats per stop) into "#rrggbb" stops. */
export function parseColormapTxt(text: string, name: string): string[] {
  const rows = text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line.length > 0)

  if (rows.length !== STOPS_PER_MAP) {
    throw new Error(`${name}: expected ${STOPS_PER_MAP} rows, found ${rows.length}`)
  }

  return rows.map((row, i) => {
    const values = row.split(/\s+/).map(Number)
    if (values.length !== 3 || values.some((v) => !Number.isFinite(v) || v < 0 || v > 1)) {
      throw new Error(`${name}: row ${i + 1} is not three numbers between 0 and 1: "${row}"`)
    }
    return floatsToHex(values[0], values[1], values[2])
  })
}

/** Zip entry path of a map's text file, e.g. ".../batlow/batlow.txt"; null if absent. */
export function findMapEntry(entryNames: string[], release: string): string | null {
  const wanted = new RegExp(`(^|/)${release}/${release}\\.txt$`)
  const hits = entryNames.filter((n) => wanted.test(n))
  if (hits.length > 1) throw new Error(`${release}: several entries match: ${hits.join(', ')}`)
  return hits[0] ?? null
}

/** Folder names of every "<x>/<x>.txt" map in the zip (used to report maps we do not offer). */
export function mapNamesInZip(entryNames: string[]): string[] {
  const names = new Set<string>()
  for (const entry of entryNames) {
    const m = entry.match(/(?:^|\/)([^/]+)\/\1\.txt$/)
    if (m) names.add(m[1])
  }
  return [...names].sort()
}

/** True for a licence or readme file at the top of the release (at most one folder deep). */
export function isLicenceEntry(entryName: string): boolean {
  const parts = entryName.split('/').filter(Boolean)
  return parts.length <= 2 && /^(licen[cs]e|readme)/i.test(parts[parts.length - 1])
}

/** Source text of src/data/colormaps.ts. Keys are sorted so the output is deterministic. */
export function renderColormapsModule(maps: Record<string, string[]>, release: ReleaseInfo): string {
  const lines = Object.keys(maps)
    .sort()
    .map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(maps[name])}`)
  return [
    '// GENERATED by scripts/build-colormaps.ts (npm run build:colormaps). Do not edit.',
    `// Fabio Crameri, Scientific colour maps v${release.version} (${release.url}), MIT licence.`,
    '',
    `export const CRAMERI_RELEASE = ${JSON.stringify(release, null, 2)} as const`,
    '',
    '/** 256 "#rrggbb" stops per map, keyed by the name shown in the app. */',
    'export const colormaps: Record<string, string[]> = {',
    lines.join(',\n'),
    '}',
    ''
  ].join('\n')
}

export interface Comparison {
  maps: number
  missingInOld: string[]
  stopsCompared: number
  stopsDiffering: number
  maxChannelDiff: number
}

/** How a freshly generated set of maps differs from the previous one (per-channel difference in 0-255 units). */
export function compareColormaps(next: Record<string, string[]>, prev: Record<string, string[]>): Comparison {
  const result: Comparison = { maps: 0, missingInOld: [], stopsCompared: 0, stopsDiffering: 0, maxChannelDiff: 0 }
  for (const name of Object.keys(next)) {
    const old = prev[name]
    if (!old) {
      result.missingInOld.push(name)
      continue
    }
    result.maps++
    next[name].forEach((hex, i) => {
      result.stopsCompared++
      if (hex === old[i]) return
      result.stopsDiffering++
      for (let c = 1; c <= 5; c += 2) {
        const d = Math.abs(parseInt(hex.slice(c, c + 2), 16) - parseInt((old[i] ?? '#000000').slice(c, c + 2), 16))
        if (d > result.maxChannelDiff) result.maxChannelDiff = d
      }
    })
  }
  return result
}
